// Command interpgen generates the regcheck and hooked interpreter variants from vm/interp_run.go
// so all three variants (fast, -tags moeluaregcheck, and debug.sethook hooked) stay mechanically in sync.
package main

import (
	"fmt"
	"os"
	"strings"
)

func main() {
	srcBytes, err := os.ReadFile("interp_run.go")
	if err != nil {
		fmt.Fprintf(os.Stderr, "interpgen: read interp_run.go: %v\n", err)
		os.Exit(1)
	}
	src := strings.ReplaceAll(string(srcBytes), "\r\n", "\n")

	regcheck := generateRegcheck(src)
	if err := os.WriteFile("interp_run_regcheck.go", []byte(regcheck), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "interpgen: write interp_run_regcheck.go: %v\n", err)
		os.Exit(1)
	}

	hooked := generateHooked(src, false)
	if err := os.WriteFile("interp_run_hooked.go", []byte(hooked), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "interpgen: write interp_run_hooked.go: %v\n", err)
		os.Exit(1)
	}

	hookedRegcheck := generateHooked(src, true)
	if err := os.WriteFile("interp_run_hooked_regcheck.go", []byte(hookedRegcheck), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "interpgen: write interp_run_hooked_regcheck.go: %v\n", err)
		os.Exit(1)
	}
}

func generateRegcheck(src string) string {
	out := "// Code generated by internal/gen/interpgen from interp_run.go; DO NOT EDIT.\n\n"
	s := strings.Replace(src, "//go:build !moeluaregcheck\n", "//go:build moeluaregcheck\n", 1)
	s = strings.Replace(s, "//go:generate go run ../internal/gen/interpgen\n", "", 1)

	// Add winGen local tracking th.stackGen on every window refresh.
	s = strings.Replace(s,
		"\tvar regs *[256]Value\n\tvar pc int\n",
		"\tvar regs *[256]Value\n\tvar pc int\n\tvar winGen uint32\n",
		1,
	)
	s = strings.ReplaceAll(s,
		"regs = th.window(ev.base)",
		"winGen = th.stackGen\n\tregs = th.window(ev.base)",
	)
	s = strings.ReplaceAll(s,
		"regs = th.window(newBase)",
		"winGen = th.stackGen\n\tregs = th.window(newBase)",
	)
	// Verify window generation, bounds, and PC on every single dispatch!
	s = strings.Replace(s,
		"\tfor {\n\t\tregs = nonNilWindow(regs)\n",
		"\tfor {\n\t\tregcheckVerifyWindow(th, ev.base, winGen, ev.bp.proto.MaxStackSize, pc, len(ev.bp.proto.Code))\n\t\tregs = nonNilWindow(regs)\n",
		1,
	)
	// Verify callFrame.dirty invariant on fast OP_CALL reuse!
	s = strings.Replace(s,
		"\t\t\t\t\t\tif nf.dirty {\n\t\t\t\t\t\t\t*nf = callFrame{}\n\t\t\t\t\t\t}\n",
		"\t\t\t\t\t\tif nf.dirty {\n\t\t\t\t\t\t\t*nf = callFrame{}\n\t\t\t\t\t\t} else {\n\t\t\t\t\t\t\tregcheckVerifyCleanFrame(nf)\n\t\t\t\t\t\t}\n",
		1,
	)
	return out + s
}

func generateHooked(src string, withRegcheck bool) string {
	out := "// Code generated by internal/gen/interpgen from interp_run.go; DO NOT EDIT.\n\n"
	if withRegcheck {
		out += "//go:build moeluaregcheck\n\n"
	} else {
		out += "//go:build !moeluaregcheck\n\n"
	}
	// Extract only the run() function and rename it to runHooked(), keeping package/imports clean.
	idx := strings.Index(src, "func (s *State) run(")
	if idx < 0 {
		panic("interpgen: could not find func (s *State) run")
	}
	end := strings.Index(src, "// execIntrinsic1")
	if end < 0 {
		panic("interpgen: could not find // execIntrinsic1 boundary")
	}
	fn := src[idx:end]
	fn = strings.Replace(fn, "func (s *State) run(", "func (s *State) runHooked(", 1)
	// Remove self-switch inside OP_CALL (already in runHooked).
	fn = strings.ReplaceAll(fn,
		"\t\t\tif (th.hookMask != 0 && !th.inHook) || s.hasInterruptControl() {\n\t\t\t\treturn s.runHooked(th, entryDepth)\n\t\t\t}\n",
		"",
	)
	// Inject instruction hook / interrupt check at top of dispatch loop!
	fn = strings.Replace(fn,
		"\tfor {\n\t\tregs = nonNilWindow(regs)\n",
		"\tfor {\n\t\tregs = nonNilWindow(regs)\n\t\tif (th.hookMask != 0 && !th.inHook) || s.hasInterruptControl() {\n\t\t\tth.frames[ev.ci].pc = pc\n\t\t\treload, err := s.checkInstructionHook(th, &ev, pc, entryDepth)\n\t\t\tif err != nil {\n\t\t\t\treturn err\n\t\t\t}\n\t\t\tif reload {\n\t\t\t\tgoto reloadFrame\n\t\t\t}\n\t\t\tregs = th.window(ev.base)\n\t\t}\n",
		1,
	)
	// Disable native intrinsic fast-inlining when call/return hooks are active so native hooks fire (db.lua:554)!
	fn = strings.Replace(fn,
		"\t\t\t} else if OptimizeEnabled && fn.IsNative() {\n",
		"\t\t\t} else if OptimizeEnabled && fn.IsNative() && th.hookMask&(HookMaskCall|HookMaskRet) == 0 {\n",
		1,
	)
	// Disable ipairs OP_TFORCALL fast path when call/return hooks are active so iterator hooks fire.
	fn = strings.Replace(fn,
		"\t\t\tif OptimizeEnabled && fn.IsNative() && fn.AsNative().Intrinsic == intrIPairsIter && regs[a+1].IsTable() {\n",
		"\t\t\tif OptimizeEnabled && fn.IsNative() && fn.AsNative().Intrinsic == intrIPairsIter && regs[a+1].IsTable() && th.hookMask&(HookMaskCall|HookMaskRet) == 0 {\n",
		1,
	)
	// Fire call hook on inline OP_CALL Lua frame push (via noinline helper to keep runHooked compact).
	fn = strings.Replace(fn,
		"\t\t\t\t\t\tpc = 0\n\t\t\t\t\t\tregs = th.window(newBase)\n\t\t\t\t\t\tcontinue\n",
		"\t\t\t\t\t\tpc = 0\n\t\t\t\t\t\tth.frames[newCI].dirty = true\n\t\t\t\t\t\tth.frames[newCI].oldPC = -1\n\t\t\t\t\t\tif reload, err := s.fireCallHook(th, newCI, nargs, nparams, entryDepth); err != nil {\n\t\t\t\t\t\t\treturn err\n\t\t\t\t\t\t} else if reload {\n\t\t\t\t\t\t\tgoto reloadFrame\n\t\t\t\t\t\t}\n\t\t\t\t\t\tregs = th.window(newBase)\n\t\t\t\t\t\tcontinue\n",
		1,
	)
	// Route OP_RETURN0 and OP_RETURN1 through execColdOp in runHooked so return hooks
	// and their error propagation share one canonical path while keeping runHooked small.
	retStart := strings.Index(fn, "\t\tcase bytecode.OP_RETURN0:\n")
	retEnd := strings.Index(fn, "\t\tcase bytecode.OP_FORLOOP:\n")
	if retStart < 0 || retEnd < 0 || retEnd <= retStart {
		panic("interpgen: could not locate OP_RETURN0..OP_RETURN1 block")
	}
	fn = fn[:retStart] + fn[retEnd:]

	if withRegcheck {
		fn = strings.Replace(fn,
			"\tvar regs *[256]Value\n\tvar pc int\n",
			"\tvar regs *[256]Value\n\tvar pc int\n\tvar winGen uint32\n",
			1,
		)
		fn = strings.ReplaceAll(fn,
			"regs = th.window(ev.base)",
			"winGen = th.stackGen\n\tregs = th.window(ev.base)",
		)
		fn = strings.ReplaceAll(fn,
			"regs = th.window(newBase)",
			"winGen = th.stackGen\n\tregs = th.window(newBase)",
		)
		fn = strings.Replace(fn,
			"\tfor {\n\t\tregs = nonNilWindow(regs)\n",
			"\tfor {\n\t\tregcheckVerifyWindow(th, ev.base, winGen, ev.bp.proto.MaxStackSize, pc, len(ev.bp.proto.Code))\n\t\tregs = nonNilWindow(regs)\n",
			1,
		)
		fn = strings.Replace(fn,
			"\t\t\t\t\t\tif nf.dirty {\n\t\t\t\t\t\t\t*nf = callFrame{}\n\t\t\t\t\t\t}\n",
			"\t\t\t\t\t\tif nf.dirty {\n\t\t\t\t\t\t\t*nf = callFrame{}\n\t\t\t\t\t\t} else {\n\t\t\t\t\t\t\tregcheckVerifyCleanFrame(nf)\n\t\t\t\t\t\t}\n",
			1,
		)
	}

	header := `package vm

import (
	"github.com/yuchanns/moelua/bytecode"
)

`
	return out + header + fn
}
